#!/usr/bin/env node
/**
 * Writes android/local.properties pointing at your Android SDK.
 *
 * local.properties is machine-specific and therefore not committed. Android Studio
 * writes it on first sync; a command-line `./gradlew` build has nothing to read.
 *
 *   node tools/setup-sdk.js                    # auto-detect
 *   node tools/setup-sdk.js "D:/Android/Sdk"   # explicit path
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

const home = os.homedir();
const candidates = [
  process.argv[2],
  process.env.ANDROID_HOME,
  process.env.ANDROID_SDK_ROOT,
  process.platform === 'win32' ? path.join(home, 'AppData', 'Local', 'Android', 'Sdk') : null,
  process.platform === 'darwin' ? path.join(home, 'Library', 'Android', 'sdk') : null,
  path.join(home, 'Android', 'Sdk'),
  '/usr/lib/android-sdk'
].filter(Boolean);

// A real SDK has at least one of these. Guards against pointing at an empty folder.
const looksLikeSdk = p =>
  fs.existsSync(p) &&
  ['platforms', 'platform-tools', 'build-tools', 'cmdline-tools', 'licenses']
    .some(sub => fs.existsSync(path.join(p, sub)));

const found = candidates.find(looksLikeSdk);

if (!found) {
  console.error('Could not find an Android SDK. Looked in:');
  candidates.forEach(c => console.error('  ' + c + (fs.existsSync(c) ? '  (exists, but no SDK folders inside)' : '')));
  console.error('\nInstall it via Android Studio (Settings > Languages & Frameworks > Android SDK),');
  console.error('or pass the path directly:  node tools/setup-sdk.js "C:/path/to/Sdk"');
  process.exit(1);
}

// Forward slashes: local.properties is a Java properties file, where a lone
// backslash is an escape character and a Windows path silently breaks.
const sdkDir = found.replace(/\\/g, '/');
const target = path.join(__dirname, '..', 'android', 'local.properties');
const body = `# Generated by tools/setup-sdk.js — machine-specific, do not commit.\nsdk.dir=${sdkDir}\n`;

fs.writeFileSync(target, body);
console.log('Android SDK found at: ' + found);
console.log('Wrote ' + target);
console.log('\nNow run:  cd android && ' +
  (process.platform === 'win32' ? 'gradlew assembleDebug' : './gradlew assembleDebug'));
