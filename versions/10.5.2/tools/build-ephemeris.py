#!/usr/bin/env python3
"""Generate the app's astronomy tables with the Swiss Ephemeris (pip install pyswisseph).

www/js/ephem-terms.js    the moment of each of the 24 solar terms, 1890-2110
www/js/ephem-planets.js  apparent geocentric longitudes of the Sun, Moon and five visible planets, 1900-2100

The app reads these tables and does not ship the Swiss Ephemeris itself. It uses the built-in Moshier mode, so no data
files are needed. Longitudes are true ecliptic of date with light-time and aberration, the definition of a solar term.
Usage: python tools/build-ephemeris.py   (run from the project root)
"""
import json
import sys

import swisseph as swe

FLAGS = swe.FLG_MOSEPH | swe.FLG_SPEED
JD0 = 2415000.0  # term times are stored as whole seconds after this Julian Day (UT)


def lon(jd, body=swe.SUN):
    return swe.calc_ut(jd, body, FLAGS)[0][0]


def cusp(target, guess):
    """The moment (JD UT) the Sun reaches a longitude, by Newton steps on the true position."""
    jd = guess
    for _ in range(12):
        diff = (lon(jd) - target + 180) % 360 - 180
        jd -= diff / 0.9856
        if abs(diff) < 1e-8:
            break
    return jd


def build_terms(first, last):
    rows = []
    for year in range(first, last + 1):
        # 立春 (315 degrees) of this year, then every 15 degrees through 大寒 of the next.
        jd = swe.julday(year, 2, 4, 0.0)
        row = []
        for i in range(24):
            jd = cusp((315 + i * 15) % 360, jd)
            row.append(round((jd - JD0) * 86400))
            jd += 15.2
        rows.append(row)
    return rows


BODIES = [('sun', swe.SUN, 4), ('moon', swe.MOON, 1), ('mercury', swe.MERCURY, 2), ('venus', swe.VENUS, 4),
          ('mars', swe.MARS, 8), ('jupiter', swe.JUPITER, 16), ('saturn', swe.SATURN, 16)]


def build_planets(first, last):
    start = swe.julday(first, 1, 1, 0.0) - 64
    end = swe.julday(last + 1, 1, 1, 0.0) + 64
    out = {'start': start, 'bodies': {}}
    for name, body, step in BODIES:
        vals, jd = [], start
        while jd <= end:
            vals.append(round(lon(jd, body) * 1000))
            jd += step
        out['bodies'][name] = {'step': step, 'lon': vals}
    return out


def main():
    print('Swiss Ephemeris', swe.version)
    terms = {'from': 1890, 'to': 2110, 'jd0': JD0, 'sec': build_terms(1890, 2110)}
    with open('www/js/ephem-terms.js', 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Solar term moments from the Swiss Ephemeris ' + swe.version + '; generated by tools/build-ephemeris.py. */\n')
        f.write('(typeof window !== "undefined" ? window : globalThis).QP_TERMS = ' + json.dumps(terms, separators=(',', ':')) + ';\n')
    planets = build_planets(1900, 2100)
    with open('www/js/ephem-planets.js', 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Apparent geocentric longitudes (0.001 degree) from the Swiss Ephemeris ' + swe.version + '; generated by tools/build-ephemeris.py. */\n')
        f.write('(typeof window !== "undefined" ? window : globalThis).QP_PLANETS = ' + json.dumps(planets, separators=(',', ':')) + ';\n')
    print('done')


if __name__ == '__main__':
    sys.exit(main())
